"""Regenerates lib/src/fold_table.dart (python3 tool/gen_fold.py, run from this package)."""
import unicodedata

rng = [*range(0xA0, 0x250), *range(0x1E00, 0x1F00), *range(0x2070, 0x20A0), *range(0x2100, 0x2200),
       *range(0xFB00, 0xFB07), *range(0xFF01, 0xFF5F), *range(0x2460, 0x24FF)]
rows = []
for cp in rng:
    n = "".join(x for x in unicodedata.normalize("NFKD", chr(cp)) if not unicodedata.combining(x))
    if n != chr(cp):
        rows.append((cp, n))
esc = lambda s: s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$")
body = ",".join(f"0x{cp:x}:'{esc(n)}'" for cp, n in rows)
open("lib/src/fold_table.dart", "w").write(
    "// Generated by tool/gen_fold.py: NFKD with combining marks removed, for U+00A0-U+24F, Latin Extended\n"
    "// Additional, super/subscripts, letterlike, enclosed, ligatures and fullwidth forms.\n"
    "const foldTable = <int, String>{" + body + "};\n")
